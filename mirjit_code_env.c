#define MIRJIT_CALL_SIMPLE_METHOD() do {			\
    rb_snum_t x = leaf ? INSN_ATTR(width) : 0;			\
    rb_snum_t y = attr_width_opt_send_without_block(0);		\
    rb_snum_t z = x - y;					\
